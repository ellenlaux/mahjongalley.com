// Regenerates netlify/functions/og-daily-assets.mjs — the art and the
// face the Daily invite card embeds (no fs paths to break between local
// dev and the Lambda bundle). Run from the repo root:
//   node scripts/gen-og-daily-assets.mjs
//
// The art is the app's own (Mahjong repo, assets/daily-deal/): the
// masthead as Ellen drew it (TheDaily.png — ink and dragon in one layer)
// and her kerned wordmarks, which print in cream on the badge. TAY Napili
// (assets/fonts) is the badge's face for the date, as in the app.
import { readFileSync, writeFileSync } from 'node:fs';

const b64 = (p) => readFileSync(p).toString('base64');
const svg = (p) => readFileSync(p, 'utf8').trim();

const out = `// GENERATED by scripts/gen-og-daily-assets.mjs — do not edit by hand.
// Base64-embedded render assets for the Daily invite card (og-daily.mjs).
export const NAPILI_B64 = '${b64('assets/fonts/TAYNapili.otf')}';
export const MASTHEAD_PNG_B64 = '${b64('assets/daily/TheDaily.png')}';
export const WORDMARK_SVG = {
  deal: ${JSON.stringify(svg('assets/daily/TheDailyWordmarkShuffle.svg'))},
  read: ${JSON.stringify(svg('assets/daily/TheDailyWordmarkRead.svg'))},
  table: ${JSON.stringify(svg('assets/daily/TheDailyWordmarkDeal.svg'))},
};
`;
writeFileSync('netlify/functions/og-daily-assets.mjs', out);
console.log('wrote netlify/functions/og-daily-assets.mjs');
