// Regenerates netlify/functions/og-receipt-assets.mjs — the moment art the
// og-receipt function embeds as base64 (one 480×480 payoff frame per win
// beat, downscaled from the keyed assets/receipt/<beat>-poster.png) and the
// receipt font. Run from the repo root after replacing any of those:
//   node scripts/gen-og-receipt-assets.mjs
// Needs ffmpeg on PATH for the downscale.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { Resvg } from '@resvg/resvg-js';

const BEATS = ['pouch-fill', 'big-money', 'burnt-joker', 'heart-eyes'];
const INK = '#1A1A2E';

/** The wordmark SVG draws in currentColor; paint it ink and render at
 *  2x the slip's width so it stays crisp on the card. */
function wordmarkPng() {
  const svg = readFileSync('assets/Mahjong-Alley.svg', 'utf8').replace(/currentColor/g, INK);
  return Buffer.from(new Resvg(svg, { fitTo: { mode: 'width', value: 668 } }).render().asPng());
}
const tmp = mkdtempSync(join(tmpdir(), 'og-receipt-'));

let out = `// GENERATED by scripts/gen-og-receipt-assets.mjs — do not edit by hand.
// Base64-embedded assets for the /og/receipt/* card: the receipt's monospace
// (Courier Prime, OFL — assets/fonts/CourierPrime-*.woff) and one 480×480
// payoff frame per win beat (downscaled from assets/receipt/<beat>-poster.png,
// the keyed transparent frame), so the function bundle is self-contained.
export const COURIER_REGULAR_B64 = '${readFileSync('assets/fonts/CourierPrime-Regular.woff').toString('base64')}';
export const COURIER_BOLD_B64 = '${readFileSync('assets/fonts/CourierPrime-Bold.woff').toString('base64')}';
// The wordmark (assets/Mahjong-Alley.svg) rasterized in receipt ink, for
// the slip's header.
export const WORDMARK_B64 = '${wordmarkPng().toString('base64')}';
export const WIN_ART_B64 = {
`;
for (const beat of BEATS) {
  const small = join(tmp, `${beat}.png`);
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', `assets/receipt/${beat}-poster.png`, '-vf', 'scale=480:480', small]);
  out += `  '${beat}': '${readFileSync(small).toString('base64')}',\n`;
}
out += `};\n`;
// The card VIDEO (og-receipt-video) composes the moment's clip over the
// slip: one small square cut per win beat (assets/receipt/<beat>-card.mp4,
// the clip stage's 720px square scaled to 300, white stage kept — the
// function keys it out at compose time), embedded so the function needs
// no file beside it on the Lambda.
out += `export const CARD_CLIP_B64 = {\n`;
for (const beat of BEATS) {
  out += `  '${beat}': '${readFileSync(`assets/receipt/${beat}-card.mp4`).toString('base64')}',\n`;
}
out += `};\n`;
writeFileSync('netlify/functions/og-receipt-assets.mjs', out);
console.log('wrote netlify/functions/og-receipt-assets.mjs');
